<?php

declare(strict_types=1);

namespace Specrig;

final class Surface
{
    public const FORMAT = 'surface/1';

    /** @var array<string, true> */
    public array $publishes = [];

    /** @var array<string, true> */
    public array $consumes = [];

    /** @var array<string, true> */
    public array $serves = [];

    /** @var array<string, true> */
    public array $calls = [];

    /** @var array<string, array<string, true>> */
    public array $clients = [];

    /** @var array<string, true> */
    public array $settings = [];

    /** @var array<string, true> */
    public array $optional = [];

    /** @var array<string, true> */
    public array $consumers = [];

    public function __construct(public string $service)
    {
    }

    public function encode(): string
    {
        return "# Generated by `specrig surface` from the service's code.\n" . Yaml::emit([
            'specrig' => self::FORMAT,
            'service' => $this->service,
            'publishes' => Strings::sorted($this->publishes),
            'consumes' => Strings::sorted($this->consumes),
            'serves' => Strings::sorted($this->serves),
            'calls' => Strings::sorted($this->calls),
            'clients' => array_map(Strings::sorted(...), Strings::byKey($this->clients)),
        ]);
    }

    public function encodeChecks(): string
    {
        return "# Generated by `specrig surface` from the service's code: what its boot is checked against.\n" . Yaml::emit([
            'specrig' => Checks::FORMAT,
            'service' => $this->service,
            'settings' => Strings::sorted($this->settings),
            'optional' => Strings::sorted($this->optional),
            'consumers' => Strings::sorted($this->consumers),
        ]);
    }

    public static function rewrite(string $file, string $body): bool
    {
        if (is_file($file) && file_get_contents($file) === $body) {
            return false;
        }
        if (!is_dir(dirname($file))) {
            mkdir(dirname($file), 0777, true);
        }
        file_put_contents($file, $body);
        return true;
    }
}
